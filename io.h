#define IO_SET_SHDN_ACTIVE()            \
    do                                  \
    {                                   \
        SUP_SHDN_SetLow();              \
        SUP_SHDN_SetDigitalOutput();    \
        SUP_SHDN_SetLow();              \
    } while (0)

#define IO_SET_SHDN_INACTIVE()          \
    do                                  \
    {                                   \
        SUP_SHDN_SetDigitalInput();     \
    } while (0)

